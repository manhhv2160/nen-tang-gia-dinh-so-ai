CREATE TABLE family (
    family_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    family_name VARCHAR(255) NOT NULL,
    description TEXT,
    origin_place VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE branch (
    branch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id BIGINT NOT NULL REFERENCES family(family_id) ON DELETE CASCADE,
    branch_name VARCHAR(255) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (family_id, branch_name)
);

CREATE TABLE member (
    member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id BIGINT NOT NULL REFERENCES family(family_id) ON DELETE CASCADE,
    branch_id BIGINT REFERENCES branch(branch_id) ON DELETE SET NULL,
    user_id BIGINT,
    full_name VARCHAR(255) NOT NULL,
    gender VARCHAR(10) NOT NULL DEFAULT 'OTHER'
        CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    date_of_birth DATE,
    date_of_death DATE,
    generation INTEGER CHECK (generation IS NULL OR generation > 0),
    occupation VARCHAR(255),
    education VARCHAR(255),
    address VARCHAR(255),
    bio TEXT,
    is_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (family_id, user_id),
    CHECK (date_of_birth IS NULL OR date_of_death IS NULL OR date_of_death >= date_of_birth)
);

CREATE TABLE parent_child_relationship (
    relationship_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_member_id BIGINT NOT NULL REFERENCES member(member_id) ON DELETE CASCADE,
    child_member_id BIGINT NOT NULL REFERENCES member(member_id) ON DELETE CASCADE,
    relationship_type VARCHAR(20) NOT NULL DEFAULT 'BIOLOGICAL'
        CHECK (relationship_type IN ('BIOLOGICAL', 'ADOPTED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (parent_member_id, child_member_id),
    CHECK (parent_member_id <> child_member_id)
);

CREATE TABLE marriage (
    marriage_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spouse_1_member_id BIGINT NOT NULL REFERENCES member(member_id) ON DELETE CASCADE,
    spouse_2_member_id BIGINT NOT NULL REFERENCES member(member_id) ON DELETE CASCADE,
    marriage_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'MARRIED'
        CHECK (status IN ('MARRIED', 'DIVORCED', 'WIDOWED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (spouse_1_member_id <> spouse_2_member_id)
);

CREATE INDEX branch_family_id_idx ON branch (family_id);
CREATE INDEX member_family_id_idx ON member (family_id);
CREATE INDEX member_branch_id_idx ON member (branch_id);
CREATE INDEX member_user_id_idx ON member (user_id);
CREATE INDEX parent_child_parent_id_idx ON parent_child_relationship (parent_member_id);
CREATE INDEX parent_child_child_id_idx ON parent_child_relationship (child_member_id);
CREATE INDEX marriage_spouse_1_idx ON marriage (spouse_1_member_id);
CREATE INDEX marriage_spouse_2_idx ON marriage (spouse_2_member_id);
