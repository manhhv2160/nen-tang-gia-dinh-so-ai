-- Schema của community-service (database community_db). Bảng: post, comment, reaction.
-- ID dùng BIGINT, không có khóa ngoại sang bảng của service khác (family_id, user_id chỉ là giá trị tham chiếu).
\connect community_db community_svc

CREATE TABLE post (
    post_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    post_type VARCHAR(20) NOT NULL DEFAULT 'GENERAL'
        CHECK (post_type IN ('NEWS', 'ANNOUNCEMENT', 'GENERAL')),
    title VARCHAR(255),
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX post_family_created_idx ON post (family_id, created_at DESC);
CREATE INDEX post_user_idx ON post (user_id);

CREATE TABLE comment (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES post(post_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX comment_post_created_idx ON comment (post_id, created_at);

CREATE TABLE reaction (
    reaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES post(post_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL,
    reaction_type VARCHAR(10) NOT NULL DEFAULT 'LIKE'
        CHECK (reaction_type IN ('LIKE', 'LOVE', 'HAHA', 'WOW', 'SAD', 'ANGRY')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (post_id, user_id)
);

