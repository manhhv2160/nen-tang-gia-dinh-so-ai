CREATE TABLE IF NOT EXISTS heritage (
 heritage_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 family_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
 heritage_type VARCHAR(30) NOT NULL CHECK (heritage_type IN ('HISTORICAL_DOC','STORY','OUTSTANDING_MEMBER','PHOTO')),
 title VARCHAR(255) NOT NULL, content TEXT, file_url TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS heritage_family_idx ON heritage(family_id,created_at);
