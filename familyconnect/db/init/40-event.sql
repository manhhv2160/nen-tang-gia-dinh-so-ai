CREATE TABLE IF NOT EXISTS event (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 family_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
 title VARCHAR(255) NOT NULL, description TEXT, location VARCHAR(255),
 start_time TIMESTAMPTZ NOT NULL, end_time TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CHECK (end_time IS NULL OR end_time >= start_time)
);
CREATE TABLE IF NOT EXISTS rsvp (
 rsvp_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id BIGINT NOT NULL REFERENCES event(event_id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL,
 status VARCHAR(10) NOT NULL CHECK (status IN ('ATTENDING','DECLINED','MAYBE')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 UNIQUE(event_id,user_id)
);
CREATE INDEX IF NOT EXISTS event_family_start_idx ON event(family_id,start_time);
